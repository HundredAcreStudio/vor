func TestClaudeMd_RoundTripDoesNotDuplicateMarkers(t *testing.T) {
	tmp, _, _ := repoFixture(t)
	if _, _, err := runRepowiseCmd(t, nil, "update", tmp); err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 3; i++ {
		if _, _, err := runRepowiseCmd(t, nil, "claude-md", tmp); err != nil {
			t.Fatalf("claude-md (run %d): %v", i, err)
		}
	}
	body, _ := os.ReadFile(filepath.Join(tmp, "CLAUDE.md"))
	s := string(body)
	if got := strings.Count(s, "REPOWISE:START"); got != 1 {
		t.Errorf("REPOWISE:START count = %d after 3 runs, want 1", got)
	}
	if got := strings.Count(s, "REPOWISE:END"); got != 1 {
		t.Errorf("REPOWISE:END count = %d after 3 runs, want 1", got)
	}
	if got := strings.Count(s, "Repowise MCP tools"); got != 1 {
		t.Errorf("'Repowise MCP tools' should appear exactly once, got %d", got)
	}
}
